def replay(rule):
    """rule(st, leg) -> True=take.  st has cum/high/consec/prior/nloss/nwin/consec_any/
    bigwin/lossL/lossS (session loss counts per side) on realized (taken) trades."""
    taken, blocked = [], []
    cur = None
    st = None
    prior = 0.0
    for x in base:
        if x["sess"] != cur:
            if st is not None:
                prior = st["cum"]
            cur = x["sess"]
            st = {"cum": 0.0, "high": 0.0, "consec": {1: 0, -1: 0}, "prior": prior,
                  "nloss": 0, "nwin": 0, "consec_any": 0, "bigwin": 0.0,
                  "loss_side": {1: 0, -1: 0}, "grosshigh": 0.0, "gross": 0.0}
        if x["mins_open"] < 3:          # guard, common to all families
            take = False
        else:
            take = rule(st, x)
        (taken if take else blocked).append(x)
        if take:
            p = x["pnl"]
            st["cum"] += p
            st["high"] = max(st["high"], st["cum"])
            st["gross"] += p + 4.18
            st["grosshigh"] = max(st["grosshigh"], st["gross"])
            if p < 0:
                st["consec"][x["dir"]] += 1
                st["nloss"] += 1
                st["consec_any"] += 1
                st["loss_side"][x["dir"]] += 1
            else:
                st["consec"][x["dir"]] = 0
                st["nwin"] += 1
                st["consec_any"] = 0
                st["bigwin"] = max(st["bigwin"], p)
    return taken, blocked


def score(taken, blocked):
    tk = {x["entry_time"][:16].replace(" ", "T") for x in taken}
    bk = {x["entry_time"][:16].replace(" ", "T") for x in blocked}
    res = {"HARD": [0, 0], "SOFT": [0, 0], "EPS": [0, 0]}
    fails = []
    for r in labels:
        key = r["entry_time"][:16]
        want = r["label"] == "TAKE"
        got = key in tk if (key in tk or key in bk) else None
        ok = (got == want)
        c = r["certainty"]
        res[c][0 if ok else 1] += 1
        if not ok:
            fails.append((c, r["label"], key))
    return res, fails


def mk_registered(X=1600.0, K=3, C=1000.0, noon=720, eve_w=360, cum_le=False):
    def rule(st, x):
        if st["prior"] <= -C and x["mins_open"] <= eve_w:
            return False
        if st["high"] >= X and x["mod"] >= noon:
            if (st["cum"] <= 0 if cum_le else st["cum"] < 0):
                return False
            if st["consec"][x["dir"]] >= K:
                return False
        return True
    return rule


def eve(st, x, C=1000.0, w=360):
    return st["prior"] <= -C and x["mins_open"] <= w


results = []


def trial(name, rule, keep_takes=False):
    tk, bk = replay(rule)
    sc, fails = score(tk, bk)
    row = {"name": name, "HARD": sc["HARD"], "SOFT": sc["SOFT"], "EPS": sc["EPS"]}
    if sc["HARD"][1] == 0:
        row["agg"] = agg(tk)
        row["takes"] = {x["entry_time"] for x in tk}
    results.append(row)
    return row, fails


